/**
 * The geometric wolf head — the site's mark. Colour comes from
 * `currentColor`. Size it with a height (or width) class plus `w-auto`
 * (or `h-auto`); the viewBox keeps its 208:286 aspect ratio.
 *
 * Decorative by default (`aria-hidden`); pass `role="img"` and `aria-label`
 * where it stands alone as meaningful content.
 *
 * Animation hooks: every stroke is a `[data-wolf-line]` polyline and every
 * filled shape a `[data-wolf-shape]` polygon, so a caller holding the ref can
 * draw the lines in and then fade the shapes up.
 */
export function Wolf({ className, ...props }: WolfProps) {
  return (
    <svg
      viewBox="0 0 208 286"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.6}
      strokeLinejoin="miter"
      strokeLinecap="round"
      aria-hidden="true"
      className={className}
      {...props}
    >
      {LINES.map((points) => (
        <polyline key={points} points={points} data-wolf-line="" />
      ))}
      {SHAPES.map((points) => (
        <polygon
          key={points}
          points={points}
          fill="currentColor"
          stroke="none"
          data-wolf-shape=""
        />
      ))}
    </svg>
  );
}
